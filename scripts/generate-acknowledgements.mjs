// Writes src/lib/acknowledgements.generated.ts from the installed packages: name, version, licence
// and home page for everything in `dependencies`. Run it after changing dependencies:
//   npm run licenses
// A test fails if a dependency is missing from the generated list or has no known licence.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));

function licenceOf(info) {
  if (typeof info.license === "string") return info.license;
  if (info.license && typeof info.license.type === "string") return info.license.type;
  if (Array.isArray(info.licenses)) return info.licenses.map((l) => l.type).join(" OR ");
  return "UNKNOWN";
}

function urlOf(info) {
  const raw =
    info.homepage ??
    (typeof info.repository === "string" ? info.repository : info.repository?.url) ??
    "";
  return String(raw)
    .replace(/^git\+/, "")
    .replace(/^git:\/\//, "https://")
    .replace(/^github:/, "https://github.com/")
    .replace(/\.git$/, "")
    .replace(/#.*$/, "");
}

const rows = Object.keys(pkg.dependencies)
  .sort((a, b) => a.localeCompare(b))
  .map((name) => {
    const info = JSON.parse(readFileSync(join(root, "node_modules", name, "package.json"), "utf8"));
    return { name, version: info.version, license: licenceOf(info), url: urlOf(info) };
  });

const out = `// Generated by scripts/generate-acknowledgements.mjs (npm run licenses). Do not edit by hand.
export type PackageLicence = { name: string; version: string; license: string; url: string };

export const PACKAGES: readonly PackageLicence[] = ${JSON.stringify(rows, null, 2)};
`;
writeFileSync(join(root, "src/lib/acknowledgements.generated.ts"), out);
console.log(`Wrote ${rows.length} packages`);
