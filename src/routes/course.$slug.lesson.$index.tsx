import { createFileRoute, useNavigate } from "@tanstack/react-router";
import { Mic } from "lucide-react";
import { useState } from "react";
import aiBot from "@/assets/ai-bot.png";
import foxMascot from "@/assets/fox-mascot.png";
import { PhoneFrame } from "@/components/PhoneFrame";
import { ScreenHeader } from "@/components/ScreenHeader";
import { buildCourse } from "@/lib/courses";
import { useProgress } from "@/lib/progress";

export const Route = createFileRoute("/course/$slug/lesson/$index")({
  head: ({ params }) => {
    const course = buildCourse(params.slug.replace(/-/g, " "));
    const lesson = course.lessons[Number(params.index) - 1] ?? course.lessons[0]!;
    return {
      meta: [
        { title: `${lesson.title} — ${course.topic} | Lamppost` },
        { name: "description", content: `${lesson.subtitle}. A short AI-generated lesson with a quick quiz.` },
        { property: "og:title", content: `${lesson.title} — Lamppost` },
        { property: "og:description", content: lesson.subtitle },
        { property: "og:type", content: "article" },
      ],
      links: [
        { rel: "canonical", href: `/course/${params.slug}/lesson/${params.index}` },
      ],
    };
  },
  component: LessonScreen,
});

function LessonScreen() {
  const { slug, index } = Route.useParams();
  const navigate = useNavigate();
  const course = buildCourse(slug.replace(/-/g, " "));
  const lessonNumber = Math.min(Math.max(Number(index) || 1, 1), course.lessons.length);
  const lesson = course.lessons[lessonNumber - 1]!;
  const { completeLesson } = useProgress();
  const [picked, setPicked] = useState<number | null>(null);

  const correct = picked === lesson.quiz.correct;

  const onContinue = () => {
    completeLesson(slug, course.topic, lessonNumber - 1, course.lessons.length);
    if (lessonNumber < course.lessons.length) {
      navigate({
        to: "/course/$slug/lesson/$index",
        params: { slug, index: String(lessonNumber + 1) },
      });
      setPicked(null);
    } else {
      navigate({ to: "/course/$slug", params: { slug } });
    }
  };

  return (
    <PhoneFrame showNav={false}>
      <ScreenHeader
        backTo="/course/$slug"
        right={
          <span className="text-xs font-bold text-muted-foreground">
            Lesson {lessonNumber} of {course.lessons.length}
          </span>
        }
      />

      <div className="px-5 pb-8">
        <span className="inline-flex items-center gap-1.5 rounded-full bg-primary-soft px-3 py-1.5 text-[11px] font-extrabold tracking-wide text-accent-foreground uppercase">
          <span aria-hidden>🔥</span> Daily lesson
        </span>
        <h1 className="mt-3 text-3xl leading-tight">{lesson.title}</h1>
        <p className="mt-1 text-sm text-muted-foreground">{lesson.subtitle}</p>

        <div className="relative mt-4 overflow-hidden rounded-3xl bg-primary-soft p-4">
          <span className="inline-block rounded-full bg-primary px-2.5 py-1 text-[10px] font-extrabold text-primary-foreground">
            Created for you
          </span>
          <p className="mt-2 max-w-[70%] text-sm font-semibold text-accent-foreground">
            This lesson was generated by AI just for you, based on your goal to learn{" "}
            {course.topic.toLowerCase()}.
          </p>
          <img
            src={aiBot}
            alt=""
            aria-hidden
            width={816}
            height={816}
            className="pointer-events-none absolute right-2 bottom-2 h-16 w-16 object-contain"
          />
        </div>

        <div className="relative mt-4 rounded-3xl bg-card p-4 shadow-card">
          <div className="flex gap-3">
            <span className="flex h-8 w-8 shrink-0 items-center justify-center rounded-full bg-hero-gradient text-sm font-extrabold text-primary-foreground">
              Q
            </span>
            <h2 className="text-base leading-snug">{lesson.quiz.question}</h2>
          </div>

          <p className="mt-4 text-xs font-semibold text-muted-foreground">Choose the best answer</p>
          <div className="mt-2 space-y-2">
            {lesson.quiz.options.map((option, i) => {
              const isPicked = picked === i;
              const isAnswer = i === lesson.quiz.correct;
              const state =
                picked === null
                  ? "border-border"
                  : isAnswer
                    ? "border-success bg-success/10"
                    : isPicked
                      ? "border-destructive bg-destructive/10"
                      : "border-border opacity-60";
              return (
                <button
                  key={option}
                  onClick={() => picked === null && setPicked(i)}
                  className={`flex w-full items-center gap-3 rounded-2xl border-2 px-4 py-3 text-left text-sm font-semibold transition-colors ${state}`}
                >
                  <span className="font-extrabold text-primary">
                    {String.fromCharCode(65 + i)}
                  </span>
                  {option}
                </button>
              );
            })}
          </div>

          {picked !== null && (
            <div className="relative mt-4 rounded-2xl bg-primary-soft p-3 pr-20">
              <p className="text-sm font-semibold text-accent-foreground">
                {correct ? "Great eye! " : "Not quite. "}
                {lesson.quiz.explanation}
              </p>
              <img
                src={foxMascot}
                alt=""
                aria-hidden
                width={816}
                height={816}
                className="pointer-events-none absolute -right-1 -bottom-1 h-20 w-20 object-contain"
              />
            </div>
          )}
        </div>

        <div className="mt-6 flex items-center gap-3">
          <button
            aria-label="Answer by voice"
            className="flex h-12 w-12 shrink-0 items-center justify-center rounded-full bg-primary-soft text-primary"
          >
            <Mic className="h-5 w-5" />
          </button>
          <button
            onClick={onContinue}
            disabled={picked === null}
            className="h-12 flex-1 rounded-full bg-hero-gradient text-base font-extrabold text-primary-foreground shadow-card transition-transform enabled:hover:scale-[1.02] disabled:opacity-50"
          >
            {lessonNumber < course.lessons.length ? "Continue" : "Finish course"}
          </button>
        </div>
      </div>
    </PhoneFrame>
  );
}
