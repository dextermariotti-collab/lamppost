const FALLBACK: Category = {
  id: "general",
  label: "General",
  icon: Sparkles,
  tile: "bg-primary-soft text-primary",
  keywords: [],
};

/** Best-guess category for a course topic, using keyword matching. */
export function categoryFor(topic: string): Category {
  const t = topic.toLowerCase();
  return CATEGORIES.find((c) => c.keywords.some((k) => t.includes(k))) ?? FALLBACK;
}
